export function getConflictsForCountry(countryId: string): Conflict[] {
  return conflicts.filter((c) =>
    c.parties.some((p) => p.countryId === countryId)
  );
}

export function getConflictsByType(type: string): Conflict[] {
  return conflicts.filter((c) => c.type === type);
}

export function getActiveConflicts(): Conflict[] {
  return conflicts.filter((c) => c.endYear === null);
}

export function getConflictsByDateRange(start: number, end: number): Conflict[] {
  return conflicts.filter(
    (c) => c.startYear <= end && (c.endYear === null || c.endYear >= start)
  );
}
